DROP DATABASE IF EXISTS SMARTCAMPUS;
CREATE DATABASE SMARTCAMPUS;
USE SMARTCAMPUS;

CREATE TABLE DEPARTMENT (
    DepartmentId VARCHAR(10) PRIMARY KEY,
    DepartmentName VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE RESOURCE_TYPE (
    TypeId INT PRIMARY KEY AUTO_INCREMENT,
    TypeName VARCHAR(50) NOT NULL UNIQUE,
    Description VARCHAR(255)
) ENGINE=InnoDB;


CREATE TABLE LOCATION (
    LocationId INT PRIMARY KEY AUTO_INCREMENT,
    BuildingName VARCHAR(100) NOT NULL,
    FloorNumber INT,
    RoomNumber VARCHAR(20) NOT NULL
) ENGINE=InnoDB;


CREATE TABLE CAMPUS_NODE (
    NodeId VARCHAR(50) PRIMARY KEY,
    NodeName VARCHAR(100) NOT NULL,
    NodeType VARCHAR(50),
    Status VARCHAR(50) DEFAULT 'Active'
) ENGINE=InnoDB;


CREATE TABLE TIME_SLOT (
    SlotId INT PRIMARY KEY AUTO_INCREMENT,
    StartTime TIME NOT NULL,
    EndTime TIME NOT NULL,
    CHECK (EndTime > StartTime)
) ENGINE=InnoDB;

 
CREATE TABLE USERS (
    UserId INT PRIMARY KEY,
    Password VARCHAR(255) NOT NULL,
    Role VARCHAR(20) NOT NULL,
    Status VARCHAR(20) DEFAULT 'Active',
    CHECK (Role IN ('Student','Faculty','Admin'))
) ENGINE=InnoDB;

CREATE TABLE RESOURCES (
    ResourceId INT PRIMARY KEY AUTO_INCREMENT,
    ResourceName VARCHAR(100) NOT NULL,
    DepartmentId VARCHAR(10) NOT NULL,
    LocationId INT NOT NULL,
    TypeId INT NOT NULL,
    Capacity INT NOT NULL,
    Status VARCHAR(30) DEFAULT 'Available',
    FOREIGN KEY (DepartmentId) REFERENCES DEPARTMENT(DepartmentId),
    FOREIGN KEY (LocationId) REFERENCES LOCATION(LocationId),
    FOREIGN KEY (TypeId) REFERENCES RESOURCE_TYPE(TypeId),
    CHECK (Capacity > 0)
) ENGINE=InnoDB;


CREATE TABLE BOOKINGS (
    BookingId INT PRIMARY KEY AUTO_INCREMENT,
    UserId INT NOT NULL,
    ResourceId INT NOT NULL,
    SlotId INT NOT NULL,
    BookingDate DATE NOT NULL,
    Purpose VARCHAR(255),
    Status VARCHAR(20) DEFAULT 'Pending',
    FOREIGN KEY (UserId) REFERENCES USERS(UserId),
    FOREIGN KEY (ResourceId) REFERENCES RESOURCES(ResourceId),
    FOREIGN KEY (SlotId) REFERENCES TIME_SLOT(SlotId),
    CHECK (Status IN ('Pending','Confirmed','Cancelled')),
    UNIQUE (ResourceId, SlotId, BookingDate)
) ENGINE=InnoDB;
 
CREATE TABLE ROUTE_HISTORY (
    RouteHistoryId INT PRIMARY KEY AUTO_INCREMENT,
    UserId INT NOT NULL,
    StartNodeId VARCHAR(50) NOT NULL,
    EndNodeId VARCHAR(50) NOT NULL,
    RouteDate DATE NOT NULL,
    Distance DECIMAL(10,2),
    RouteStatus VARCHAR(30) DEFAULT 'Completed',
    FOREIGN KEY (UserId) REFERENCES USERS(UserId),
    FOREIGN KEY (StartNodeId) REFERENCES CAMPUS_NODE(NodeId),
    FOREIGN KEY (EndNodeId) REFERENCES CAMPUS_NODE(NodeId)
) ENGINE=InnoDB;
 
CREATE TABLE CAMPUS_EDGE (
    EdgeId VARCHAR(10) PRIMARY KEY,
    FromNodeId VARCHAR(50) NOT NULL,
    ToNodeId VARCHAR(50) NOT NULL,
    Distance DECIMAL(10,2) NOT NULL,
    Latency INT,
    Capacity INT,
    Availability VARCHAR(30) DEFAULT 'Available',
    FOREIGN KEY (FromNodeId) REFERENCES CAMPUS_NODE(NodeId),
    FOREIGN KEY (ToNodeId) REFERENCES CAMPUS_NODE(NodeId)
) ENGINE=InnoDB;

 
